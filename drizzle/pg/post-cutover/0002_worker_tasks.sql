  "workerId" integer NOT NULL,
  "answer" boolean,
  "animalTag" varchar(40),
  "stockKinds" text[],
  "purchaseKind" varchar(20) CHECK ("purchaseKind" IN ('vaccine', 'medicine', 'other')),
  "itemName" varchar(120),
  "amount" numeric(12, 2) CHECK ("amount" > 0),
  "animalId" integer,
  "confirmedAt" timestamp(0),
  "confirmedBy" integer,
  "createdAt" timestamp(0) NOT NULL DEFAULT now(),
  "updatedAt" timestamp(0) NOT NULL DEFAULT now(),
  "createdBy" integer,
  "deletedAt" timestamp(0),
  "deletedBy" integer,
  "version" integer NOT NULL DEFAULT 1,
