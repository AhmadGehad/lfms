      WHEN 'animal_sick' THEN "animalTag" IS NOT NULL
      WHEN 'stock_needed' THEN "answer" IS NOT NULL AND ("answer" = false OR cardinality("stockKinds") > 0)
      ELSE "answer" IS NOT NULL
    END
